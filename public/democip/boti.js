  /* --- resorte critico-amortiguado ---------------------------------------- */
  function Spring(value, stiffness, damping) {
    this.value = value || 0; this.velocity = 0; this.target = value || 0;
    this.stiffness = stiffness; this.damping = damping;
  }
  Spring.prototype.step = function (dt) {
    var a = (this.target - this.value) * this.stiffness - this.velocity * this.damping;
    this.velocity += a * dt; this.value += this.velocity * dt; return this.value;
  };
  Spring.prototype.impulse = function (amount) { this.velocity += amount; };

  function clamp(v, a, b) { return Math.max(a, Math.min(b, v)); }
  function mix(a, b, t) { return a + (b - a) * t; }
  function smoothstep(t) { return t * t * (3 - 2 * t); }

  function transform(el, cx, cy, x, y, rot, sx, sy) {
    if (!el) return;
    el.setAttribute('transform',
      'translate(' + x.toFixed(3) + ' ' + y.toFixed(3) + ') translate(' + cx + ' ' + cy + ') ' +
      'rotate(' + rot.toFixed(3) + ') scale(' + sx.toFixed(5) + ' ' + sy.toFixed(5) + ') ' +
      'translate(' + (-cx) + ' ' + (-cy) + ')');
  }

